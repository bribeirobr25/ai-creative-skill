#!/usr/bin/env python3
"""Offline design simulation for the Video Director evaluation (no model calls, no spend).

Question: for plausible specialization effects, judge noise and judge bias, how often would each evaluation design
(scenarios x runs per arm) give a clear reading of "does the Director's guidance beat a generalist", and how often
a clear but wrong one? It sizes the design; it says nothing about the Director itself.

Model (every parameter is a labelled assumption; see the report for which ones the recorded evidence informs):
- Scenario s has a true specialization effect delta_s = mu + tau * z_s (z ~ N(0, 1)), in units of the run-to-run
  standard deviation of one arm's quality on one scenario. tau > 0 means the effect depends on the conditions.
- Run r pairs one Director run with one generalist run on the same scenario: d = delta_s + e_D - e_G (e ~ N(0, 1)).
  Runs of one scenario share delta_s, so they are correlated, not independent.
- Each pair is judged twice with positions swapped: y = d + bias + pos * b_pos + sigma_j * eta (eta ~ N(0, 1)),
  pos = +1 then -1. A call prefers the Director when y > 0. bias is a judge's lean toward the Director (same model
  family, recognisable format, length); position swapping cancels b_pos, not bias.
- Scenario score = mean preference over its pairs and calls, minus 0.5. Estimate = mean over scenarios.
  A 95% interval comes from a cluster bootstrap that resamples whole scenarios.
- Reading: "clear, Director" if the interval is above 0, "clear, generalist" if below, otherwise inconclusive.
  This classifies how informative a design is. It is not the readiness rule, which is not a win-rate threshold.

Usage: python3 evaluation-design-simulation.py [--n 2000] [--boot 1000] [--seed 20261104] [--out FILE]
"""
import argparse
import itertools
import math
from pathlib import Path

import numpy as np

DESIGNS = [  # (label, scenarios, runs per arm)
    ('3 x 2 (12 transcripts, the 2026-11-03 plan)', 3, 2),
    ('6 x 1 (12 transcripts)', 6, 1),
    ('12 x 1 (24 transcripts)', 12, 1),
    ('8 x 2 (32 transcripts)', 8, 2),
    ('24 x 1 (48 transcripts)', 24, 1),
    ('12 x 2 (48 transcripts)', 12, 2),
]
MU = [0.0, 0.25, 0.5, 1.0]
TAU = [0.0, 0.5]
SIGMA_J = [0.5, 1.5]
BIAS = [0.0, 0.3]
B_POS = 0.3


def win_probability(mu):
    """P(one Director run beats one generalist run on the same scenario), before judge noise, with tau = 0."""
    return 0.5 * (1 + math.erf(mu / 2))  # d ~ N(mu, 2): P(d > 0) = Phi(mu / sqrt 2)


def judge_agreement(sigma_j, rng, n=200_000):
    """Implied rate at which two independent judges agree on the winner of a typical pair (mu = 0.5, tau = 0)."""
    d = 0.5 + rng.normal(size=n) * math.sqrt(2)
    a = d + sigma_j * rng.normal(size=n) > 0
    b = d + sigma_j * rng.normal(size=n) > 0
    return float((a == b).mean())


def simulate(scenarios, runs, mu, tau, sigma_j, bias, n, boot, rng, chunk=250):
    clear_d = clear_g = 0
    for start in range(0, n, chunk):
        m = min(chunk, n - start)
        delta = mu + tau * rng.normal(size=(m, scenarios, 1))
        d = delta + rng.normal(size=(m, scenarios, runs)) - rng.normal(size=(m, scenarios, runs))
        calls = [d + bias + pos * B_POS + sigma_j * rng.normal(size=d.shape) > 0 for pos in (1, -1)]
        score = (calls[0].mean(axis=2) + calls[1].mean(axis=2)) / 2 - 0.5        # (m, scenarios)
        idx = rng.integers(0, scenarios, size=(m, boot, scenarios))
        boots = np.take_along_axis(score[:, None, :].repeat(boot, axis=1), idx, axis=2).mean(axis=2)
        lo, hi = np.percentile(boots, [2.5, 97.5], axis=1)
        clear_d += int((lo > 0).sum())
        clear_g += int((hi < 0).sum())
    return clear_d / n, clear_g / n


def detection_table():
    rows = []
    for n in (6, 12, 24, 48):
        seen = ['%.0f%%' % (100 * (1 - (1 - p) ** n)) for p in (0.05, 0.10, 0.20, 0.30)]
        upper = 1 - 0.05 ** (1 / (n + 1))  # 95% upper bound on the rate after 0 failures, Beta(1, 1 + n)
        rows.append('| %d | %s | %.0f%% |' % (n, ' | '.join(seen), 100 * upper))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--n', type=int, default=2000)
    ap.add_argument('--boot', type=int, default=1000)
    ap.add_argument('--seed', type=int, default=20261104)
    ap.add_argument('--out', default=str(Path(__file__).with_name('evaluation-design-simulation-2026-11-04-results.md')))
    a = ap.parse_args()
    rng = np.random.default_rng(a.seed)

    out = ['# Evaluation design simulation · generated results', '',
           'Generated by `evaluation-design-simulation.py --n %d --boot %d --seed %d` (numpy %s). Do not edit by hand; '
           'the interpretation is in `evaluation-design-simulation-2026-11-04.md`.' % (a.n, a.boot, a.seed, np.__version__),
           '', 'Monte Carlo error: at most about +/-%.1f points per cell.' % (100 * math.sqrt(0.25 / a.n) * 1.96), '',
           '## Assumed parameters', '',
           '| mu | P(Director run beats generalist run), no judge noise |', '|---|---|']
    out += ['| %.2f | %.0f%% |' % (mu, 100 * win_probability(mu)) for mu in MU]
    out += ['', '| sigma_j | Implied agreement of two independent judges on a pair (mu = 0.5) |', '|---|---|']
    out += ['| %.1f | %.0f%% |' % (s, 100 * judge_agreement(s, rng)) for s in SIGMA_J]
    out += ['', 'Position bias b_pos = %.1f in every condition (cancelled by swapping).' % B_POS, '',
            '## Results', '', 'Each cell: % clear for the Director / % clear for the generalist; the rest is inconclusive.', '']
    for tau, sigma_j, bias in itertools.product(TAU, SIGMA_J, BIAS):
        out += ['### tau = %.1f, sigma_j = %.1f, judge bias toward the Director = %.1f' % (tau, sigma_j, bias), '',
                '| Design | ' + ' | '.join('mu = %.2f' % mu for mu in MU) + ' |', '|---|' + '---|' * len(MU)]
        for label, s, r in DESIGNS:
            cells = ['%.0f / %.0f' % tuple(100 * x for x in simulate(s, r, mu, tau, sigma_j, bias, a.n, a.boot, rng))
                     for mu in MU]
            out.append('| %s | %s |' % (label, ' | '.join(cells)))
        out.append('')
    out += ['## Robustness checks: chance of seeing a failure at least once', '',
            'Closed form, no simulation. Rows: runs per arm that face the check. Last column: the 95% upper bound '
            'on the failure rate if none is seen.', '',
            '| Runs | rate 5% | rate 10% | rate 20% | rate 30% | Upper bound after 0 failures |', '|---|---|---|---|---|---|']
    out += detection_table()
    Path(a.out).write_text('\n'.join(out) + '\n')
    print('wrote', a.out)


if __name__ == '__main__':
    main()
