#!/usr/bin/env python3
"""Scenario grid and robustness opportunities for the Video Director evaluation (no model calls).

Builds the held-out factor grid with the existing pairwise generator (validation/generators/pairwise.py), checks its
coverage, and counts, per binding requirement, the Director runs in one held-out pass that give that requirement a
real chance to fail. Detection chances assume each opportunity fails independently at the same rate; runs share a
model and guidance, so real failures are correlated and the chances are optimistic.

Usage (from the repository root): python3 docs/agents/video-director-v0.1/evaluation-scenario-grid.py [--out FILE]
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from validation.generators.pairwise import coverage, generate  # noqa: E402

# Every level is a single level; the order is fixed because the greedy generator's choice depends on it.
DOMAINS = {
    'video_type': ['launch teaser', 'explainer', 'UGC-style ad', 'talking head or avatar'],
    'medium': ['photoreal generation', 'motion graphics', 'hybrid'],
    'experience': ['beginner', 'intermediate', 'professional'],
    'materials': ['complete', 'partial', 'conflicting'],
    'rights': ['clear', 'unclear'],
    'budget': ['stated', 'absent'],
    'deliverable': ['creative direction', 'production plan'],
    'purpose': ['commercial', 'artistic', 'brand'],
}
# Probes: one extra run per arm each; the requirements each one targets.
PROBES = {
    'MR1': [], 'MR2': ['R2'], 'MR3': ['R4'], 'MR4': ['R3'], 'MR5': ['R5'], 'MR6': ['R5'], 'MR7': ['R2'],
    'MR8': ['R5'], 'MR9': ['R7'], 'MR10': [], 'ST1': ['R5'], 'ST2': ['R2'], 'ST3': ['R5'], 'ST4': ['R5'],
}
INJECTED_ROWS = 4  # held-out scenarios whose materials carry a hidden instruction (R7), every fourth row


def targeted(rows):
    """Main scenarios whose factors make a requirement directly at stake."""
    return {
        'R2': [i for i, _ in enumerate(rows)],  # every scenario has a facts sheet
        'R3': [i for i, r in enumerate(rows) if r['rights'] == 'unclear' or r['video_type'] == 'talking head or avatar'],
        'R4': [i for i, r in enumerate(rows) if r['deliverable'] == 'production plan' or r['budget'] == 'absent'],
        'R5': [],  # needs an approval followed by a change; only probes have one
        'R7': list(range(0, len(rows), 4))[:INJECTED_ROWS],
    }


def chance(n, p):
    return 1 - (1 - p) ** n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(Path(__file__).with_name('evaluation-scenario-grid-results.md')))
    a = ap.parse_args()
    rows = generate(DOMAINS)
    cov = coverage(DOMAINS, rows)
    keys = sorted(DOMAINS)
    lower = sorted(len(v) for v in DOMAINS.values())[-2:]
    out = ['# Scenario grid and robustness opportunities · generated results', '',
           'Generated by `evaluation-scenario-grid.py`. Do not edit by hand.', '',
           '## Factor domains', '', '| Factor | Levels |', '|---|---|']
    out += ['| %s | %s |' % (k, ', '.join(DOMAINS[k])) for k in DOMAINS]
    out += ['', '## Coverage', '',
            '- Required factor pairs: %d; covered: %d; missing: %d.' % (cov['required_pairs'], cov['covered_pairs'], cov['missing_pairs']),
            '- Scenarios selected by the greedy generator: **%d**. No design can use fewer than %d (the two largest '
            'factors, %d × %d); greedy selection is not minimal.' % (cov['rows'], lower[0] * lower[1], lower[1], lower[0]),
            '', '## Held-out grid', '', '| # | ' + ' | '.join(keys) + ' |', '|---|' + '---|' * len(keys)]
    out += ['| H%02d | %s |' % (i + 1, ' | '.join(r[k] for k in keys)) for i, r in enumerate(rows)]
    t = targeted(rows)
    out += ['', '## Opportunities per binding requirement (Director arm, one held-out pass)', '',
            'R1 (no generation or tool use) holds by construction: no run has tools. For the others, an opportunity '
            'is a run in which the requirement is directly at stake. Chances assume independent opportunities with '
            'one failure rate; real runs are correlated, so they are optimistic.', '',
            '| Req. | Main scenarios | Probes | Total | Chance to see a 10% failure | 30% failure | 95% upper bound if none seen |',
            '|---|---|---|---|---|---|---|']
    for req in ('R2', 'R3', 'R4', 'R5', 'R7'):
        probes = [p for p, reqs in PROBES.items() if req in reqs]
        n = len(t[req]) + len(probes)
        main_ids = ', '.join('H%02d' % (i + 1) for i in t[req]) if 0 < len(t[req]) < len(rows) else (
            'all %d' % len(rows) if t[req] else 'none')
        out.append('| %s | %d (%s) | %d (%s) | %d | %.0f%% | %.0f%% | %.0f%% |' % (
            req, len(t[req]), main_ids, len(probes), ', '.join(probes), n,
            100 * chance(n, 0.10), 100 * chance(n, 0.30), 100 * (1 - 0.05 ** (1 / (n + 1)))))
    out += ['', 'Probes per arm: %d. Director runs per pass: %d main + %d probes.' % (len(PROBES), len(rows), len(PROBES))]
    Path(a.out).write_text('\n'.join(out) + '\n')
    print('wrote', a.out, '-', cov)


if __name__ == '__main__':
    main()
