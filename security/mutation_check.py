#!/usr/bin/env python3
"""Mutation check for the publication guard (finding PR20-P1-3).

Each mutant disables one detection rule or helper in publication_guard; the guard's test suite must then fail.
A mutant that survives means no test would notice that rule breaking.

    python3 security/mutation_check.py [--report security/mutation-report.md]
"""
import argparse
import io
import re
import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import publication_guard as pg  # noqa: E402

NEVER = re.compile(r'(?!)')


def mutants():
    for i, (name, _) in enumerate(pg.BLOCK_RULES):
        yield 'BLOCK rule %s disabled' % name, 'BLOCK_RULES', pg.BLOCK_RULES[:i] + ((name, NEVER),) + pg.BLOCK_RULES[i + 1:]
    for i, (name, _) in enumerate(pg.REVIEW_RULES):
        yield 'REVIEW rule %s disabled' % name, 'REVIEW_RULES', pg.REVIEW_RULES[:i] + ((name, NEVER),) + pg.REVIEW_RULES[i + 1:]
    yield 'private file names never match', 'PRIVATE_FILENAME', NEVER
    yield 'no review suffixes', 'REVIEW_FILE_SUFFIXES', ()
    yield 'base64 re-scan disabled', '_base64_hidden_secrets', lambda *a, **k: []
    yield 'split-token join disabled', '_split_token_findings', lambda *a, **k: []
    yield 'email detection disabled', 'has_reviewable_email', lambda *a, **k: False
    yield 'media magic always accepted', '_has_valid_media_magic', lambda *a, **k: True


def suite_fails():
    loader = unittest.TestLoader()
    suite = loader.loadTestsFromName('test_publication_guard')
    result = unittest.TextTestRunner(stream=io.StringIO(), verbosity=0).run(suite)
    return not result.wasSuccessful()


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--report', type=Path)
    a = ap.parse_args(argv)
    if suite_fails():
        print('baseline test suite fails; fix it before measuring mutants')
        return 2
    rows = []
    for label, attr, value in mutants():
        original = getattr(pg, attr)
        setattr(pg, attr, value)
        try:
            killed = suite_fails()
        finally:
            setattr(pg, attr, original)
        rows.append((label, killed))
        print('%-8s %s' % ('killed' if killed else 'SURVIVED', label))
    killed = sum(k for _, k in rows)
    summary = 'Mutation score: %d of %d mutants killed (%.0f%%)' % (killed, len(rows), 100 * killed / len(rows))
    print(summary)
    if a.report:
        lines = ['# Publication guard mutation report', '', summary + '.', '',
                 'Generated by `python3 security/mutation_check.py --report security/mutation-report.md`. In-process mutants;',
                 'the real-Git CLI tests run the unmutated guard in a subprocess, so they cannot kill a mutant.', '',
                 '| Mutant | Result |', '|---|---|'] + ['| %s | %s |' % (l, 'killed' if k else '**survived**') for l, k in rows]
        a.report.write_text('\n'.join(lines) + '\n')
    return 0 if killed == len(rows) else 1


if __name__ == '__main__':
    sys.exit(main())
